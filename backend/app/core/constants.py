from __future__ import annotations

#: 勋章总数。原型「已解锁 6 / 18 枚」的分母。
#:
#: **Phase D 的勋章注册表长度必须等于它** —— 那时会补一条测试锁死这件事。
#: 现在先独立成常量，是因为个人中心在 Phase A 就要返回这个分母。
BADGE_TOTAL = 18

#: 历史卷轴每页条数（方案 §5.5「复合索引 + 分页 20 条」）。
SCROLL_PAGE_SIZE = 20
SCROLL_PAGE_SIZE_MAX = 50

#: 复习提醒的估算口径（对应原型 04·8 的三宫格）。
#:
#: 原型「3 题 → 预计 2 分钟 / 可得 +60 XP」：
#: - 用时：40 秒/题 → 3 题 = 120 秒 = 2 分钟（向上取整）
#: - XP：按题型最低满分 20 计 → 3 题 = 60。取最低值是把预期说低，
#:   实际结算只会更多，不会出现「说给 60 结果给 40」这种失信。
SECONDS_PER_REVIEW_QUESTION = 40
XP_PER_REVIEW_QUESTION = 20

#: 昵称在界面上提示的长度区间（数据库列上限见 `utils/crypto.NICKNAME_MAX_LEN`）。
NICKNAME_MIN_LEN = 1
NICKNAME_UI_MAX_LEN = 16

#: 单局用时的上限：4 小时。
#:
#: `started_at` / `finished_at` 是**客户端上报**的，服务端只能换算、不能验证。
#: 一台时间错乱的设备足以报出「这一局用了 37 天」，而那会直接污染数据看板的
#: 「平均单局用时」，并且 `attempts.duration_ms` 是 INT UNSIGNED（上限约 49 天）——
#: 越界会让 INSERT 在严格模式下直接失败，用户看到的是「交卷失败」。
#: 因此超出部分一律夹到上限并记警告，而不是拒绝交卷：答题记录比这个数字重要得多。
MAX_SESSION_MS = 4 * 60 * 60 * 1000

#: 客户端时间戳的合理下界（2020-01-01T00:00:00Z）。
#:
#: 用来挡掉「毫秒与秒搞混」这类错误：传了秒级时间戳（约 1.7e9）会落在这里面，
#: 而它对应的日期是 1970 年，画到看板上会多出一根莫名其妙的柱子。
MIN_CLIENT_TIMESTAMP_MS = 1577836800000

#: 知识领域「点亮」的掌握度阈值（方案 §8.3）。
MASTERY_LIT_THRESHOLD = 90

#: 错题复习的下次到期间隔（天），下标即 `wrong_questions.stage`（方案 §8.4）。
REVIEW_INTERVALS_DAYS: tuple[int, ...] = (1, 2, 4, 7, 15, 30)

#: 连续答对几次复习即移出错题队列（方案 §8.4「连续两次复习答对」）。
REVIEW_MASTERED_STAGE = 2
