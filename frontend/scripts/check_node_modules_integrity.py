#!/usr/bin/env python
"""扫描 node_modules，找出「包在、但入口文件缺」的残缺包。

## 为什么需要它

`npm install` 的**完整性校验只到包级别**（目录在、版本对就算 OK），
不会核对包内单个文件是否齐全。所以安装被中断过（进程被杀 / 多进程互锁）之后，
会留下一种很难查的坏状态：

    node_modules/@tarojs/helper/dist/index.js.map   ← 在
    node_modules/@tarojs/helper/dist/index.d.ts     ← 在
    node_modules/@tarojs/helper/dist/index.js       ← 缺！而 index.js 里正是 require 它

随后 `npm install` 会报「up to date」并**正常退出**，错误推迟到 `taro build` 才炸，
报的却是 `Cannot find module './dist/index.js'` —— 看起来像源码问题，实际是依赖残缺。

## 它能发现的三类问题

1. **入口缺失**：`package.json` 的 `main` / `exports` 指向的文件不存在 → 致命，必崩。
2. **存根目标缺失**：入口文件存在，但它只是 `module.exports = require('./x')` 的存根，
   而 `./x` 不存在 → 同样致命，且**第 1 类检查发现不了**（入口文件本身是存在的）。
   `@tarojs/*` 系列大量使用这种存根写法，所以这一类不能省。
3. **安装残留**：`.core-alyZBO2e` 这类点开头的临时暂存目录 —— 中断的安装留下的垃圾。

`types` / `typings` 缺失单独列为**警告**：它不影响运行，但会让 TS 编译报错，
所以有诊断价值却不该和致命问题混在一起。

用法（在 frontend/ 目录下）：

    python scripts/check_node_modules_integrity.py
    python scripts/check_node_modules_integrity.py --root node_modules.broken   # 扫描被让位的旧树

退出码：0 = 未发现致命问题；1 = 有残缺或残留（便于串进构建前置检查）。
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NODE_MODULES = ROOT / "node_modules"

#: 无扩展名时依次尝试的后缀
SUFFIXES = ("", ".js", ".mjs", ".cjs", ".json", ".ts", ".d.ts")

#: 存根文件的最大体积（超过这个尺寸就不是存根了）
STUB_MAX_BYTES = 400

#: 匹配 require('./xxx') / require("./xxx")，只认相对路径
REQUIRE_RE = re.compile(r"""require\(\s*['"](\.[^'"]*)['"]\s*\)""")

#: 跟多少层存根。@tarojs 的存根通常只有一层
MAX_STUB_HOPS = 3


def _iter_package_dirs(base: Path):
    """遍历 node_modules 下的包目录，含 @scope 一层。"""
    if not base.is_dir():
        return
    for child in sorted(base.iterdir()):
        if not child.is_dir():
            continue
        name = child.name
        if name == "node_modules":
            continue
        if name.startswith("@"):
            for scoped in sorted(child.iterdir()):
                if scoped.is_dir():
                    yield scoped
        else:
            yield child


def _package_dirs() -> list[Path]:
    """主 node_modules 下的所有包目录（不含嵌套，嵌套由调用方递归）。"""
    return list(_iter_package_dirs(NODE_MODULES))


def _all_package_dirs() -> list[Path]:
    """含嵌套 node_modules 的全部包目录。"""
    out: list[Path] = []
    seen: set[Path] = set()

    def walk(root: Path) -> None:
        for pkg in _iter_package_dirs(root):
            if pkg in seen:
                continue
            seen.add(pkg)
            out.append(pkg)
            nested = pkg / "node_modules"
            if nested.is_dir():
                walk(nested)

    walk(NODE_MODULES)
    return out


def _flatten_exports(node: object) -> list[str]:
    out: list[str] = []
    if isinstance(node, str):
        out.append(node)
    elif isinstance(node, dict):
        for key, value in node.items():
            # 条件对象的 key 是 import/require/default/node/...，值才是路径
            if isinstance(value, str) and key in ("types", "typings"):
                continue
            out.extend(_flatten_exports(value))
    elif isinstance(node, list):
        for value in node:
            out.extend(_flatten_exports(value))
    return out


def _resolve(base_dir: Path, rel: str) -> Path | None:
    """把相对路径按 Node 的规则解析成实际文件；失败返回 None。

    `base_dir` 是**解析基准目录**，这一点是易错处：
      - `package.json` 的 `main` / `exports` 以**包根**为基准；
      - 文件内部的 `require('./x')` 以**该文件所在目录**为基准。
    第一版一律用包根做基准，于是把 `debug/src/index.js` 里的
    `require('./browser.js')` 解析成了 `debug/browser.js`（不存在），
    而真实位置是 `debug/src/browser.js` —— 一下子误报 50 多个包。

    解析顺序**必须**照抄 Node 的三步，不能颠倒：
      ① 精确文件（`lib/foo`）
      ② 文件 + 扩展名（`lib/foo.js`）
      ③ 当成目录找 index（`lib/foo/index.js`）

    ②③ 的顺序也很容易写反。反了会误报 `spdy-transport` / `websocket-driver` 这类包：
    它们的 main 是 `lib/spdy-transport`，而 `lib/` 下**同时存在**
    `spdy-transport.js` 和 `spdy-transport/` 目录 —— 先查目录就会因为目录里没有
    index.js 而误判为「入口不存在」。实测这两个包是完好的。
    """
    if not rel:
        return None
    if rel.startswith("./"):
        rel = rel[2:]

    # `require('./')` / `main: "."` 指向**目录自身**，Node 会取该目录的 index。
    # 不能当成无效路径直接返回 None —— 那会把 `es-object-atoms/ToObject.js`
    # （内容是 `require('./')`）误判成「存根目标缺失」。
    if rel in ("", ".", "/"):
        for suffix in SUFFIXES:
            if not suffix:
                continue
            candidate = base_dir / f"index{suffix}"
            if candidate.is_file():
                return candidate
        return None

    target = base_dir / rel

    # ① 精确文件
    if target.is_file():
        return target

    # ② 文件 + 扩展名
    for suffix in SUFFIXES:
        if not suffix:
            continue
        candidate = base_dir / f"{rel}{suffix}"
        if candidate.is_file():
            return candidate

    # ③ 目录 index
    if target.is_dir():
        for suffix in SUFFIXES:
            if not suffix:
                continue
            candidate = target / f"index{suffix}"
            if candidate.is_file():
                return candidate

    return None


def _stub_target(entry: Path) -> tuple[bool, Path | None]:
    """判断 entry 是不是存根文件，并解析它 require 的目标。

    返回 `(是否存根, 目标路径)`。**必须把这两件事分开返回**：
    第一版只用 `Path | None` 表示，结果「不是存根」和「是存根但目标缺失」
    返回了同一个 None，调用方无从区分 —— 于是真正的坏状态被静默当成正常。
    这正是 `@tarojs/helper` 逃过检查的原因（它的 index.js 是 85 字节的存根，
    `require('./dist/index.js')` 指向的文件已经没了）。

    存根判据：文件很小 + 含 require('./相对路径')。两者都满足才算，
    避免把真正的实现文件（同样可能 require 别的东西）误判成存根。
    目标以 **entry 所在目录** 为基准解析（见 `_resolve` 的说明）。
    """
    try:
        if entry.stat().st_size > STUB_MAX_BYTES:
            return False, None
        text = entry.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return False, None

    matches = REQUIRE_RE.findall(text)
    if not matches:
        return False, None
    return True, _resolve(entry.parent, matches[0])


def _follow_stub(entry: Path) -> Path | None:
    """沿存根链走到底，确认最终目标文件真实存在。

    返回最终目标路径；若中途某个存根的目标缺失则返回 None（= 坏了）。
    `@tarojs/*` 系列大量使用「入口只是 require 到 dist/」的写法，
    所以这条链必须跟，否则整个 @tarojs 的残缺都查不出来。
    """
    current = entry
    for _hop in range(MAX_STUB_HOPS):
        is_stub, target = _stub_target(current)
        if not is_stub:
            return current  # 走到实现文件了
        if target is None:
            return None  # 是存根，但目标不存在 → 坏
        current = target
    # 走满 MAX_STUB_HOPS 仍在 require，视为正常（链太长不代表坏）
    return current


def _check_package(pkg_dir: Path) -> tuple[list[str], list[str]]:
    """返回 (致命问题列表, 警告列表)。"""
    fatal: list[str] = []
    warns: list[str] = []

    pkg_json_path = pkg_dir / "package.json"
    if not pkg_json_path.is_file():
        return fatal, warns
    try:
        pkg_json = json.loads(pkg_json_path.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return fatal, warns

    # ---- 运行时入口：main + exports ----
    # **只检查「包自己声明过的」入口，绝不替它兜底猜 index.js。**
    # 第一版会猜，结果全是误报：node_modules 里存在大量**本来就没有 JS 入口**的包 ——
    #   `@esbuild/win32-x64`  负载是 esbuild.exe（纯二进制）
    #   `node-releases`       负载是 data/ 下的 JSON（纯数据）
    #   `@types/archy`        纯类型包，main 声明为空字符串
    #   `type-fest`           纯类型包，只有 types
    # 替这些包假设一个 index.js，只会制造噪音、让人不再相信扫描结果。
    # 猜错的代价还体现在反面：真正的坏状态（声明了却缺文件、或存根目标缺失）
    # 恰恰都是**有声明**的，所以不猜反而抓得更准。
    runtime: list[str] = []
    main = pkg_json.get("main")
    if isinstance(main, str) and main.strip():
        runtime.append(main)
    runtime.extend(_flatten_exports(pkg_json.get("exports")))

    resolved_any = False
    for rel in runtime:
        # package.json 的入口以**包根**为基准
        entry = _resolve(pkg_dir, rel)
        if entry is None:
            continue
        resolved_any = True

        # 入口存在还不够 —— 若它只是个存根，必须把存根链跟到底
        final = _follow_stub(entry)
        if final is None:
            fatal.append(f"入口 {rel} 是存根，但它 require 的目标不存在")
            continue

    if runtime and not resolved_any:
        fatal.append("声明了入口但文件不存在：" + "、".join(runtime[:3]))

    # ---- 类型入口：单独作为警告 ----
    for field in ("types", "typings"):
        value = pkg_json.get(field)
        if isinstance(value, str) and value and _resolve(pkg_dir, value) is None:
            warns.append(f"{field} 指向的文件不存在：{value}")

    return fatal, warns


def _find_staging_leftovers() -> list[Path]:
    """找出安装中断留下的点开头暂存目录（如 @babel/.core-alyZBO2e）。"""
    leftovers: list[Path] = []
    search_roots = [NODE_MODULES]
    for pkg in _package_dirs():
        if pkg.parent.name.startswith("@"):
            search_roots.append(pkg.parent)
    seen: set[Path] = set()
    for root in search_roots:
        if root in seen or not root.is_dir():
            continue
        seen.add(root)
        try:
            for child in root.iterdir():
                if child.is_dir() and child.name.startswith(".") and child.name not in (".bin", ".cache"):
                    leftovers.append(child)
        except OSError:
            continue
    return sorted(leftovers)


def main() -> int:
    parser = argparse.ArgumentParser(description="扫描 node_modules 的入口文件完整性")
    parser.add_argument(
        "--root",
        default="node_modules",
        help="要扫描的目录，相对 frontend/ 解析；默认 node_modules",
    )
    args = parser.parse_args()

    global NODE_MODULES  # noqa: PLW0603 — 一次性的 CLI 覆盖，不值得为它引入类
    NODE_MODULES = (ROOT / args.root).resolve()

    if not NODE_MODULES.is_dir():
        print(f"[x] 未找到 {NODE_MODULES}，请先在 frontend/ 下执行 npm install")
        return 1

    print("=" * 78)
    print("node_modules 完整性扫描")
    print(f"目标：{NODE_MODULES.relative_to(ROOT) if ROOT in NODE_MODULES.parents else NODE_MODULES}")
    print("=" * 78)

    fatal_report: list[tuple[str, list[str]]] = []
    warn_report: list[tuple[str, list[str]]] = []

    for pkg_dir in _all_package_dirs():
        fatal, warns = _check_package(pkg_dir)
        rel = str(pkg_dir.relative_to(ROOT))
        if fatal:
            fatal_report.append((rel, fatal))
        if warns:
            warn_report.append((rel, warns))

    leftovers = _find_staging_leftovers()

    if fatal_report:
        print(f"\n❌ 致命：{len(fatal_report)} 个包加载时会崩\n")
        for rel, items in fatal_report:
            print(f"  - {rel}")
            for item in items:
                print(f"      {item}")

    if warn_report:
        print(f"\n⚠️  警告：{len(warn_report)} 个包缺类型声明（不影响运行，影响 tsc）\n")
        for rel, items in warn_report[:10]:
            print(f"  - {rel}")
            for item in items:
                print(f"      {item}")
        if len(warn_report) > 10:
            print(f"  ... 另有 {len(warn_report) - 10} 个")

    if leftovers:
        print(f"\n🧹 安装残留：{len(leftovers)} 个暂存目录（可直接删除）\n")
        for item in leftovers[:10]:
            print(f"  - {item.relative_to(ROOT)}")
        if len(leftovers) > 10:
            print(f"  ... 另有 {len(leftovers) - 10} 个")

    if not (fatal_report or warn_report or leftovers):
        print("\n  ✅ 未发现问题")
        return 0

    if fatal_report or leftovers:
        print("\n  修复：这是中断安装留下的残缺树，重建比逐个补更快 ——")
        print("        mv node_modules node_modules.broken && npm ci")
    print("=" * 78)
    return 1 if (fatal_report or leftovers) else 0


if __name__ == "__main__":
    raise SystemExit(main())
