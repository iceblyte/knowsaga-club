/**
 * 大厅空态：预设的热门问题（**点一下填进输入框**，用户再自己点「召唤副本」）。
 *
 * ## 为什么是「问题」而不是「知识点」
 *
 * 原来这三条是 `AI 入门` / `RAG 是什么` / `近代史纲要` —— 一个知识点名词。
 * 名词的问题是：填进输入框之后还得自己补成一句话才算一个能出题的主题，
 * 等于没省事。现在每条本身就是一句可以直接出题的话，填进去不用改就能发。
 *
 * ⚠️ 「词表长什么样」与「点下去召不召唤」是**两件独立的事**，别绑在一起读：
 * 点击行为在 `pages/hall` 的 `fillPreset`，2026-09-22 与 2026-09-23 各改过一次
 * （行为变更表见那个文件的文件头）。本文件只负责词表本身。
 *
 * ## ⚠️ 每一条都必须 ≥ `INPUT_MIN_LEN`（8 字）
 *
 * 这不是排版要求，是**契约**：后端 `text_cleaner.validate_input` 按**清洗后**
 * 的长度判 4001。原来「点一下直接召唤」时，改短的后果是「点一下弹一个内容太短的报错」；
 * 现在改成只填不发之后更严格 —— 变成「用户按了『召唤副本』却被拦下」，
 * 而那是**用户自己按的**，界面必须保证预设的每一条都能直接过闸。
 * `AI 入门` 只有 4 个字符，正是当初被换掉的原因之一。
 */
export const MOCK_SUGGESTIONS = [
  'AI 入门该先学什么',
  'RAG 是什么，为什么有用',
  '近代史纲要该怎么复习',
  '大模型的幻觉是什么'
] as const

