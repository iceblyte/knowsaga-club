/**
 * 大厅空态：预设的热门问题（**点一下直接召唤副本**）。
 *
 * ## 为什么改成「问题」而不是「知识点」
 *
 * 原来这三条是 `AI 入门` / `RAG 是什么` / `近代史纲要` —— 一个知识点名词。
 * 它们点下去只是**填进输入框**，用户还得自己再点一次「召唤副本」。
 * 空态给 chip 的本意是「减少键盘输入、提高首题生成率」，而只填不发
 * 把这一步省下来的功夫又还回去了。现在它们读起来就是一句可以直接出题的话，
 * 点一下即走（`pages/hall` 的 `summonWithPreset`）。
 *
 * ## ⚠️ 每一条都必须 ≥ `INPUT_MIN_LEN`（8 字）
 *
 * 这不是排版要求，是**契约**：后端 `text_cleaner.validate_input` 按**清洗后**
 * 的长度判 4001。改短了的后果不是「按钮变灰」而是「点一下弹一个内容太短的报错」。
 * `AI 入门` 只有 4 个字符，正是原来不能一键发送的原因之一。
 */
